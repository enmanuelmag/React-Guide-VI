export const codeLines = [
  "import { useState } from 'react'",
  "import { useQuery } from '@tanstack/react-query'",
  "import { searchMedia } from './api/media'",
  "import { toMediaSearchCardModel }",
  "  from './adapters/media-search-item-to-card-model'",
  "",
  "export function SearchDemo() {",
  "  // Borrador",
  "  const [draftQuery, setDraftQuery] = useState('')",
  "  const [draftMediaType, setDraftMediaType] = useState('movie')",
  "  const [submittedSearch, setSubmittedSearch] = useState(null)",
  "",
  "  // Confirmar el pedido",
  "  function handleSubmit(event) {",
  "    event.preventDefault()",
  "",
  "    if (draftQuery.trim().length < 2) {",
  "      return",
  "    }",
  "",
  "    setSubmittedSearch({",
  "      query: draftQuery.trim(),",
  "      mediaType: draftMediaType,",
  "    })",
  "  }",
  "",
  "  // Identidad y procedimiento",
  "  const input = submittedSearch ?? { query: '', mediaType: 'movie' }",
  "",
  "  const query = useQuery({",
  "    queryKey: ['media', 'search', input],",
  "    queryFn: () => searchMedia(input),",
  "    enabled: submittedSearch !== null && input.query.length >= 2,",
  "  })",
  "",
  "  // Vista derivada; el DTO sigue en Query",
  "  const cards = (query.data ?? []).map(toMediaSearchCardModel)",
  "",
  "  function getMessage() {",
  "",
  "    if (submittedSearch === null) {",
  "      return 'Envía una búsqueda'",
  "    }",
  "",
  "    if (query.isLoading) {",
  "      return 'Cargando'",
  "    }",
  "",
  "    if (query.isError) {",
  "      return 'No pudimos buscar'",
  "    }",
  "",
  "    if (cards.length === 0) {",
  "      return 'Sin resultados'",
  "    }",
  "",
  "    return 'Resultados'",
  "  }",
  "",
  "  const message = getMessage()",
  "",
  "  // Interfaz",
  "  return (",
  "    <main>",
  "      <form onSubmit={handleSubmit}>",
  "        <input",
  "          value={draftQuery}",
  "          onChange={e => setDraftQuery(e.target.value)}",
  "        />",
  "",
  "        <select",
  "          value={draftMediaType}",
  "          onChange={e => setDraftMediaType(e.target.value)}",
  "        >",
  "          <option value=\"movie\">Películas</option>",
  "          <option value=\"series\">Series</option>",
  "        </select>",
  "",
  "        <button>Buscar</button>",
  "      </form>",
  "",
  "      <p>{message}</p>",
  "",
  "      <ul>",
  "        {cards.map(card => (",
  "          <li key={card.key}>",
  "            {card.title} · {card.releaseLabel}",
  "          </li>",
  "        ))}",
  "      </ul>",
  "    </main>",
  "  )",
  "}"
];
